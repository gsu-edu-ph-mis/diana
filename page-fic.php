				<h3 class="h4 mb-4">From Prototype to Product: WVFIC's Impact and Successes</h3>
				<p>Through its research and development activities, WVFIC has successfully developed numerous food prototypes, including vacuum-fried green mango chips, banana chips, and kamote sticks, as well as sprayed dried food products. Demonstrating its commitment to tangible impact, WVFIC has recently ventured into commercialization. In partnership with DOST-PCIERRD, a toll manufacturing facility is being established to produce commercially three matured technologies: vacuum-fried green mango chips, vacuum-fried banana chips, and vacuum-fried kamote sticks. This initiative, under the DOST SMART Food Value Chain Program, involves a collaboration with the MSME partner, Keitzsteinhorn Food Production, which will be responsible for marketing these innovative products. During the 2023 Manggahan Festival and GSU University Week, Keitzsteinhorn Food Production already utilized the vacuum fryer housed at WVFIC to produce and sell these products, demonstrating the immediate impact of the center's support.</p>
				

				<h3 class="h4 mb-4">Highlighting Research and Development Projects</h3>
				<p>WVFIC has undertaken several significant projects since its inception, each contributing to the growth and capability of the center and the region's food industry:</p>
				<ul>
					<li><strong>Year 1 & 2 (March 2014 – September 2016)</strong> which focused on the establishment and initial operationalization of the Food Innovation Center in Western Visayas, with the cooperation of the Western Visayas Consortium for Industry and Energy Research and Development (WVCIERD) Inc.</li>
					<li><strong>Year 3 (January 2017 – September 2018)</strong> which aimed at strengthening the operations and building the capability of the FIC.</li>
					<li><strong>Year 4 (May 2029 – May 30, 2021)</strong> which focused on intensifying research and development activities and expanding the services offered by the FIC.</li>
					<li><strong>Year 5 (2021 - 2024)</strong> which focused on upgrading the production of vacuum-fried fruits and vegetables at the Western Visayas Food Innovation Center through the “DOST SMART FOOD VALUE CHAIN PROGRAM FOR THE NEW NORMAL.”</li>
					<li><strong>Year 6 (April 2025 - May 2027)</strong> that involves the establishment of a Food Analytical Laboratory at the GSU-Western Visayas Food Innovation Center to support its toll manufacturing and R&D projects.</li>
				</ul>

				<p>These projects have resulted and continue to result in an impressive list of product prototypes. Between September 2015 and December 31, 2021, the center developed numerous prototypes showcasing the diverse capabilities of its equipment, including vacuum fryers, spray dryers, freeze dryers, and water retorts. Notable examples include various flavored vacuum-fried sweet potato, banana, and cassava sticks, green mango and other fruit chips, calamansi and roselle powder, freeze-dried fruits and vegetables, and ready-to-drink beverages. Ongoing efforts in subsequent years, including the upgrading of vacuum-fried production and the establishment of a food analytical laboratory, are expected to further expand the range of product innovations.</p>

				<h3 class="h4 mb-4">Collaboration and Partnerships: A Cornerstone of WVFIC's Success</h3>
				<p>WVFIC's achievements are underpinned by strong collaborations and partnerships. The initial partnership with DOST 6 was crucial for its establishment. The ongoing collaboration with DOST-PCIERRD for the toll manufacturing project, involving a significant investment and national-level support, further highlights the center's importance. The partnership with Keitzsteinhorn Food Production exemplifies how WVFIC bridges the gap between research and industry application, facilitating technology transfer and commercialization. Furthermore, WVFIC actively engages with other stakeholders, including the Department of Trade and Industry (DTI) and the Provincial Office for Agricultural Services (POAS), to promote a supportive ecosystem for the food industry. Focus Group Discussions (FGDs) have been conducted with these stakeholders to analyze the value and supply chain of key commodities like sweet potato, green mango, and saba banana, ensuring a sustainable approach to development.</p>

